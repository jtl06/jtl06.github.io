"""Render quarto/core-to-core/article.md to quarto/core-to-core/index.html for Eleventy.

The page shell (title, nav, widget assets) comes from the site layout; this writes only the
article body. Figures are served from /c2c/figures/ (see .eleventy.js).
usage: python3 scripts/render-c2c.py   (or npm run render:c2c)
"""
import re
from pathlib import Path

import markdown

ROOT = Path(__file__).resolve().parent.parent / "quarto" / "core-to-core"
FIG = "/c2c/figures/"

src = (ROOT / "article.md").read_text()
src = re.sub(r"<!--.*?-->\n?", "", src, flags=re.S)  # drop the EDIT notes
body = markdown.markdown(src, extensions=["footnotes", "tables", "md_in_html", "fenced_code"],
                         extension_configs={"footnotes": {"BACKLINK_TEXT": "↩"}})
body = body.replace("<h1>Core to Core is not Core to Core</h1>\n", "")  # the layout owns the title

# A plain image paragraph becomes a wide figure with the alt text as its caption.
body = re.sub(r'<p><img alt="([^"]*)" src="([^"]+)" ?/?></p>',
              r'<figure class="wide"><img src="\2" alt="\1"><figcaption>\1</figcaption></figure>', body)

# Display math: one plain equation line (no math renderer on the site).
body = re.sub(r"<p>\$\$\s*(.*?)\s*\$\$</p>", r'<p class="equation">\1</p>', body, flags=re.S)

# Wide tables scroll inside their own box on narrow screens.
body = body.replace("<table>", '<div class="table-scroll" tabindex="0"><table>').replace("</table>", "</table></div>")

# Relative figure paths (src, href, widget data-*src) point at the passthrough copy.
body = re.sub(r'((?:src|href|data-[a-z-]*src)=")figures/', r"\1" + FIG, body)

# Animations: full-colour WebP first, GIF as the fallback.
body = re.sub(r'<img src="(' + re.escape(FIG) + r'[^"]+)\.gif"([^>]*)>',
              r'<picture><source srcset="\1.webp" type="image/webp"><img src="\1.gif"\2></picture>', body)

for path in re.findall(re.escape(FIG) + r'[^"?#]+', body):
    if not (ROOT / "figures" / path[len(FIG):]).is_file():
        raise SystemExit(f"render-c2c: missing figure {path}")

out = ROOT / "index.html"
out.write_text(f"<!-- generated by scripts/render-c2c.py from article.md; do not edit -->\n"
               f"<html><body>\n{body}\n</body></html>\n")
print("wrote", out.relative_to(ROOT.parent.parent), len(body), "bytes")
